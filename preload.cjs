'use strict';
const { contextBridge, ipcRenderer } = require('electron');
const invoke = (method, ...args) => ipcRenderer.invoke(`trace-atlas:${method}`, ...args);
const subscribe = (event, callback) => {
  if (typeof callback !== 'function') throw Error('Expected an event callback.');
  const handler = (_event, payload) => callback(payload);
  ipcRenderer.on(`trace-atlas:${event}`, handler);
  return () => ipcRenderer.removeListener(`trace-atlas:${event}`, handler);
};
contextBridge.exposeInMainWorld('traceAtlas', Object.freeze({
  getState: () => invoke('get-state'),
  setWindowAppearance: mode => invoke('window-appearance', mode),
  getDiagramInfo: () => invoke('diagram-info'),
  getTraceDiagram: () => invoke('diagram-trace'),
  setDiagramAppearance: (preset, appearance) => invoke('diagram-appearance', preset, appearance),
  getDiagramExample: type => invoke('diagram-example', type),
  getDiagramComparisonExample: () => invoke('diagram-comparison-example'),
  renderDiagram: options => invoke('diagram-render', options),
  openDiagram: (id, appearance) => invoke('diagram-open', id, appearance),
  importDiagram: () => invoke('diagram-import'),
  exportDiagram: (id, format) => invoke('diagram-export', id, format),
  detectAttachment: () => invoke('detect-attachment'),
  startAttachment: options => invoke('start-attachment', options),
  stopAttachment: () => invoke('stop-attachment'),
  restartAndRecapture: () => invoke('restart-and-recapture'),
  getTraceHealth: () => invoke('get-trace-health'),
  getSnapshots: () => invoke('get-snapshots'),
  pinTrace: (graphId, name) => invoke('pin-trace', graphId, name),
  openSnapshot: id => invoke('open-snapshot', id),
  removeSnapshot: id => invoke('remove-snapshot', id),
  importTrace: () => invoke('import-trace'),
  compareSnapshots: (leftId, rightId) => invoke('compare-snapshots', leftId, rightId),
  openInEditor: options => invoke('open-in-editor', options),
  getTracingSetup: () => invoke('tracing-setup'),
  previewTracingSetup: options => invoke('preview-tracing-setup', options),
  applyTracingSetup: id => invoke('apply-tracing-setup', id),
  undoTracingSetup: options => invoke('undo-tracing-setup', options),
  getProductInfo: () => invoke('product-info'),
  getWorkspaces: () => invoke('get-workspaces'),
  saveWorkspace: options => invoke('save-workspace', options),
  openWorkspace: id => invoke('open-workspace', id),
  removeWorkspace: id => invoke('remove-workspace', id),
  exportDiagnostics: () => invoke('export-diagnostics'),
  connectRepository: () => invoke('connect-repository'),
  openApp: url => invoke('open-app', url),
  openDemo: () => invoke('open-demo'),
  openBrokenDemo: () => invoke('open-broken-demo'),
  inspect: () => invoke('inspect'),
  capture: selector => invoke('capture', selector),
  refresh: () => invoke('refresh'),
  refreshSource: () => invoke('rescan-source'),
  setIndexProfile: profile => invoke('set-index-profile', profile),
  getProjectMap: () => invoke('get-project-map'),
  clearProjectMap: () => invoke('clear-project-map'),
  getLocalModels: () => invoke('get-local-models'),
  explainAgent: request => invoke('explain-agent', request),
  cancelAgent: () => invoke('cancel-agent'),
  readSource: options => invoke('read-source', options),
  setPreviewBounds: bounds => invoke('preview-bounds', bounds),
  setPreviewMaximized: value => invoke('preview-maximized', value),
  setPreviewResizing: value => invoke('preview-resizing', value),
  exportTrace: graphId => invoke('export-trace', graphId),
  exportKit: () => invoke('export-kit'),
  onState: callback => subscribe('state', callback),
  onAgentProgress: callback => subscribe('agent-progress', callback),
  onSelection: callback => subscribe('selection', callback),
  onTrace: callback => subscribe('trace', callback),
  onError: callback => subscribe('error', callback),
}));
