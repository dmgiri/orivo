import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
import {mkdir,writeFile,readFile} from 'node:fs/promises';
import path from 'node:path';
import {_electron as electron} from 'playwright-core';
const require=createRequire(import.meta.url),root=path.resolve(import.meta.dirname,'..');
const id='index-profile-'+Date.now(),artifacts=path.join(root,'.tmp',id),fixture=path.join(artifacts,'project');
await mkdir(fixture,{recursive:true});
const source='// fixture padding\n'.repeat(18000)+'export const visible=true;\n';
await writeFile(path.join(fixture,'large.js'),source);
await writeFile(path.join(fixture,'credentials.json'),'{"password":"excluded"}');
const env={...process.env,TRACE_ATLAS_TEST_PROFILE:id,ORIVO_START_MODE:'welcome'};delete env.ELECTRON_RUN_AS_NODE;
let app;const errors=[];
try{
 app=await electron.launch({executablePath:require('electron'),args:[root],env});
 const page=await app.firstWindow();page.on('pageerror',error=>errors.push(error.message));
 await page.waitForFunction(()=>typeof window.traceAtlas?.setIndexProfile==='function');
 await app.evaluate(({dialog},folder)=>{dialog.showOpenDialog=async()=>({canceled:false,filePaths:[folder]});},fixture);
 await page.evaluate(()=>window.traceAtlas.connectRepository());
 await page.evaluate(()=>document.querySelectorAll('dialog[open]').forEach(d=>d.close()));
 assert.equal((await page.evaluate(()=>window.traceAtlas.getState())).repository.fileCount,0);
 await page.locator('#trace-tools-button').click();
 await page.locator('#source-index-profile').selectOption('large');
 await page.locator('#source-index-apply').click();
 await page.waitForFunction(()=>document.querySelector('#tool-health')?.textContent.includes('1 indexed files'));
 let state=await page.evaluate(()=>window.traceAtlas.getState());
 assert.equal(state.repository.fileCount,1,JSON.stringify(state.repository));assert.equal(state.repository.limits.files,25000);
 assert.ok((await page.evaluate(()=>window.traceAtlas.readSource({path:'large.js',line:18001}))).code.includes('visible'));
 await page.locator('#trace-tools-dialog .dialog-close').click();
 await page.evaluate(()=>window.traceAtlas.connectRepository());
 state=await page.evaluate(()=>window.traceAtlas.getState());assert.equal(state.repository.profile,'large');
 await assert.rejects(page.evaluate(()=>window.traceAtlas.setIndexProfile('unlimited')),/supported source index profile/);
 const pref=JSON.parse(await readFile(path.join(root,'.tmp','test-profile-'+id,'source-index-profile.json'),'utf8'));assert.equal(pref.profile,'large');
 await app.close();app=null;
 app=await electron.launch({executablePath:require('electron'),args:[root],env});
 const reopened=await app.firstWindow();await reopened.waitForFunction(()=>typeof window.traceAtlas?.setIndexProfile==='function');
 await app.evaluate(({dialog},folder)=>{dialog.showOpenDialog=async()=>({canceled:false,filePaths:[folder]});},fixture);
 await reopened.evaluate(()=>window.traceAtlas.connectRepository());
 assert.equal((await reopened.evaluate(()=>window.traceAtlas.getState())).repository.profile,'large');
 assert.equal(await readFile(path.join(fixture,'large.js'),'utf8'),source);assert.deepEqual(errors,[]);
 const report={passed:true,checks:['Large profile applies through Health UI','Excluded credentials stay excluded','Larger indexed source can be opened','Invalid profiles rejected','Preference survives process restart','Connected source unchanged'],errors};
 await writeFile(path.join(artifacts,'result.json'),JSON.stringify(report,null,2));console.log(JSON.stringify(report,null,2));
}finally{if(app)await app.close();}
